bool OperatorNameLess(const OperatorSignature* left, const OperatorSignature* right) {
  return left->opName < right->opName;
}

/// A C++ identifier spelled as the op name must be: an ASCII upper-case letter first, then only
/// ASCII letters and digits. The generated types hang the op name verbatim into their names, so
/// anything else fails the build instead of producing a broken identifier.
bool IsPascalIdentifier(const std::string& text) {
  if (text.empty() || text[0] < 'A' || text[0] > 'Z') {
    return false;
  }
  for (const char c : text) {
    const bool letter = (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z');
    const bool digit = c >= '0' && c <= '9';
    if (!letter && !digit) {
      return false;
    }
  }
  return true;
}

/// The SLType spelling of one GLSL type, or nullptr outside the supported set.
const char* SLTypeNameOf(const std::string& glslType) {
  if (glslType == "float") {
    return "Float";
  }
  if (glslType == "int") {
    return "Int";
  }
  if (glslType == "vec2") {
    return "Float2";
  }
  if (glslType == "vec3") {
    return "Float3";
  }
  if (glslType == "vec4") {
    return "Float4";
  }
  if (glslType == "ivec4") {
    return "Int4";
  }
  if (glslType == "mat3") {
    return "Float3x3";
  }
  if (glslType == "mat4") {
    return "Float4x4";
  }
  if (glslType == "sampler2D") {
    return "Texture2DSampler";
  }
  if (glslType == "sampler2DRect") {
    return "Texture2DRectSampler";
  }
  return nullptr;
}

/// The UniformFormat spelling of one GLSL type, or nullptr outside the supported set.
const char* UniformFormatNameOf(const std::string& glslType) {
  return SLTypeNameOf(glslType);
}

/// The C++ field type of one uniform-side parameter, or nullptr when the mapping fails.
std::string UniformFieldCppType(const OperatorParamInfo& param) {
  if (param.type == "float") {
    return "float";
  }
  if (param.type == "int") {
    return "int32_t";
  }
  if (param.type == "vec2") {
    return "std::array<float, 2>";
  }
  if (param.type == "vec3") {
    return "std::array<float, 3>";
  }
  if (param.type == "vec4") {
    return "std::array<float, 4>";
  }
  if (param.type == "ivec4") {
    return "std::array<int32_t, 4>";
  }
  if (param.type == "mat3") {
    return "Matrix";
  }
  if (param.type == "mat4") {
    return "std::array<float, 16>";
  }
  return {};
}

/// The flattened element length of one uniform array field: std140 keeps every element on a
/// 16-byte stride, so both vec4 and ivec4 count 4 scalars per element.
std::string UniformArrayFieldCppType(const OperatorParamInfo& param) {
  const uint32_t length = param.arrayCount * 4;
  return param.type == "ivec4" ? "std::array<int32_t, " + std::to_string(length) + ">"
                               : "std::array<float, " + std::to_string(length) + ">";
}

const char* RoleName(OperatorParamRole role) {
  switch (role) {
    case OperatorParamRole::In:
      return "In";
    case OperatorParamRole::Uniform:
      return "Uniform";
    case OperatorParamRole::UniformArray:
      return "UniformArray";
    case OperatorParamRole::Sampler:
      return "Sampler";
  }
  return "Uniform";
}

bool HasIntLiterals(const OperatorSignature& signature) {
  for (const auto& param : signature.params) {
    if (param.intLiteral) {
      return true;
    }
  }
  return false;
}

bool HasUniformMembers(const OperatorSignature& signature) {
  for (const auto& param : signature.params) {
    if (param.role == OperatorParamRole::Uniform) {
      return true;
    }
  }
  return false;
}

/// Writes text only when it differs from the file's current content, so an unchanged input leaves
/// the timestamp alone and the build does not recompile consumers for nothing.
bool WriteIfChanged(const std::string& path, const std::string& text, std::string* error) {
  std::ifstream existing(path, std::ios::binary);
  if (existing.is_open()) {
    std::string current((std::istreambuf_iterator<char>(existing)),
                        std::istreambuf_iterator<char>());
    existing.close();
    if (current == text) {
      return true;
    }
  }
  std::ofstream out(path, std::ios::binary | std::ios::trunc);
  if (!out.is_open()) {
    *error = "cannot write " + path;
    return false;
  }
  out.write(text.data(), static_cast<std::streamsize>(text.size()));
  if (!out) {
    *error = "cannot write " + path;
    return false;
  }
  return true;
}

void AppendHeaderTypes(std::string* text) {
  *text += "/// The role one parameter plays when a processor emits the operator call.\n";
  *text += "enum class GeneratedParamRole : uint8_t { In, Uniform, UniformArray, Sampler };\n";
  *text += "\n";
  *text += "struct GeneratedOperatorParam {\n";
  *text += "  const char* name = \"\";\n";
  *text += "  const char* type = \"\";\n";
  *text += "  GeneratedParamRole role = GeneratedParamRole::Uniform;\n";
  *text += "  uint32_t arrayCount = 0;\n";
  *text += "  /// An /*@in*/ int literal: the printers fold it into the text and the processor key\n";
  *text += "  /// must encode the value.\n";
  *text += "  bool intLiteral = false;\n";
  *text += "};\n";
  *text += "\n";
  *text += "struct GeneratedOperatorDesc {\n";
  *text += "  OperatorID id = INVALID_OPERATOR_ID;\n";
  *text += "  const char* opName = \"\";\n";
  *text += "  const char* functionName = \"\";\n";
  *text += "  bool vertexStage = false;\n";
  *text += "  const GeneratedOperatorParam* params = nullptr;\n";
  *text += "  uint32_t paramCount = 0;\n";
  *text += "};\n";
  *text += "\n";
  *text += "extern const GeneratedOperatorDesc kGeneratedOperators[];\n";
  *text += "extern const uint32_t kGeneratedOperatorCount;\n";
  *text += "\n";
  *text += "/// Returns the descriptor of the named operator, or null when the name is not declared.\n";
  *text += "const GeneratedOperatorDesc* FindGeneratedOperator(const std::string& opName);\n";
  *text += "\n";
}

/// The Emit signature's parameter list: one ValueID per In / Sampler argument, one int32_t per
/// int literal, in declaration order.
void AppendEmitSignatureParams(const OperatorSignature& signature, std::string* text) {
  bool first = true;
  for (const auto& param : signature.params) {
    if (param.role == OperatorParamRole::In) {
      if (!first) {
        *text += ", ";
      }
      if (param.intLiteral) {
        *text += "int32_t ";
      } else {
        *text += "ValueID ";
      }
      *text += param.name;
      first = false;
    } else if (param.role == OperatorParamRole::Sampler) {
      if (!first) {
        *text += ", ";
      }
      *text += "ValueID ";
      *text += param.name;
      first = false;
    }
  }
}

void AppendUniformsStruct(const OperatorSignature& signature, std::string* text) {
  if (!HasUniformMembers(signature)) {
    return;
  }
  *text += "/// The uniform side of the ";
  *text += signature.opName;
  *text += " operator: one field per declared uniform member, uploaded by base name.\n";
  *text += "struct ";
  *text += signature.opName;
  *text += "Uniforms {\n";
  for (const auto& param : signature.params) {
    if (param.role == OperatorParamRole::Uniform) {
      *text += "  ";
      *text += UniformFieldCppType(param);
      *text += " ";
      *text += param.name;
      *text += " = {};\n";
    } else if (param.role == OperatorParamRole::UniformArray) {
      *text += "  ";
      *text += UniformArrayFieldCppType(param);
      *text += " ";
      *text += param.name;
      *text += " = {};\n";
    }
  }
  *text += "\n";
  *text += "  /// Writes every member into the stage's uniform block by its base name; the name\n";
  *text += "  /// suffix mangling stays inside UniformData (the same route onSetData uses today).\n";
  *text += "  void upload(UniformData* uniformData) const;\n";
  *text += "};\n";
  *text += "\n";
}

void AppendEmitClass(const OperatorSignature& signature, std::string* text) {
  *text += "/// The call-side glue of the ";
  *text += signature.opName;
  *text += " operator.\n";
  *text += "struct ";
  *text += signature.opName;
  *text += "Op {\n";
  *text += "  /// The mangled uniform names Emit declared, for the text route's call arguments.\n";
  *text += "  struct UniformNames {\n";
  for (const auto& param : signature.params) {
    if (param.role == OperatorParamRole::Uniform || param.role == OperatorParamRole::UniformArray) {
      *text += "    std::string ";
      *text += param.name;
      *text += ";\n";
    }
  }
  *text += "  };\n";
  *text += "\n";
  *text += "  /// Declares the operator's uniforms (on the text-side uniform handler; the IR\n";
  *text += "  /// interface picks them up from there) and emits the operator call. textNames may be\n";
  *text += "  /// null when the caller does not assemble the text route. Returns the result value\n";
  *text += "  /// id, or the invalid id when the builder rejects the call.\n";
  if (HasIntLiterals(signature)) {
    *text += "  /// key must encode: every int literal argument below (";
    bool first = true;
    for (const auto& param : signature.params) {
      if (param.intLiteral) {
        if (!first) {
          *text += ", ";
        }
        *text += param.name;
        first = false;
      }
    }
    *text += ").\n";
  }
  if (HasUniformMembers(signature)) {
    *text += "  /// Declares the operator's uniforms once. A second call returns immediately, so both\n";
    *text += "  /// the linked-call path and the inline paths can call it unconditionally; every program\n";
    *text += "  /// form then carries the full uniform set the upload side fills. textNames must not be\n";
    *text += "  /// null.\n";
    *text += "  static void EnsureUniforms(ProgramIRBuilder* ir, UniformHandler* uniformHandler,\n";
    *text += "                            UniformNames* textNames);\n";
    *text += "\n";
  }
  *text += "  static ValueID Emit(ProgramIRBuilder* ir, UniformHandler* uniformHandler,\n";
  *text += "                      UniformNames* textNames, ";
  AppendEmitSignatureParams(signature, text);
  *text += ");\n";
  *text += "};\n";
  *text += "\n";
}

void AppendParamTables(const std::vector<const OperatorSignature*>& sorted, std::string* text) {
  for (const OperatorSignature* signature : sorted) {
    *text += "const GeneratedOperatorParam k";
    *text += signature->opName;
    *text += "Params[] = {\n";
    for (const auto& param : signature->params) {
      *text += "    {\"";
      *text += param.name;
      *text += "\", \"";
      *text += param.type;
      *text += "\", GeneratedParamRole::";
      *text += RoleName(param.role);
      *text += ", ";
      *text += std::to_string(param.arrayCount);
      *text += ", ";
      *text += param.intLiteral ? "true" : "false";
      *text += "},\n";
    }
    *text += "};\n";
    *text += "\n";
  }
}

/// The runtime manifest table, serialized from the same signatures as the glue: the id
/// enumerators stay hand-written in OperatorManifest.h (stable values); a missing enumerator or a
/// signature drift fails the compile instead of surfacing at runtime.
void AppendManifestTable(const std::vector<const OperatorSignature*>& sorted, std::string* text) {
  *text += "const OperatorDesc kGeneratedOperatorDescs[] = {\n";
  for (const OperatorSignature* signature : sorted) {
    *text += "    {OperatorID::";
    *text += signature->opName;
    *text += ", \"";
    *text += signature->opName;
    *text += "\", \"";
    *text += signature->functionName;
    *text += "\", SLType::";
    *text += SLTypeNameOf(signature->returnType);
    *text += ",\n     {";
    bool first = true;
    for (const auto& param : signature->params) {
      if (!first) {
        *text += ", ";
      }
      first = false;
      if (param.arrayCount > 0) {
        *text += "OperatorParam(SLType::";
        *text += SLTypeNameOf(param.type);
        *text += ", true, ";
        *text += std::to_string(param.arrayCount);
        *text += ")";
      } else {
        *text += "OperatorParam(SLType::";
        *text += SLTypeNameOf(param.type);
        *text += ")";
      }
    }
    *text += "}, {";
    first = true;
    for (const auto& include : signature->includes) {
      if (!first) {
        *text += ", ";
      }
      first = false;
      *text += "\"";
      *text += include;
      *text += "\"";
    }
    *text += "}},\n";
  }
  if (sorted.empty()) {
    *text += "    // No //@op annotations yet; the manifest table stays empty until the migration\n";
    *text += "    // marks its first operator.\n";
  }
  *text += "};\n";
  *text += "\n";
  *text += "const uint32_t kGeneratedOperatorDescCount = ";
  *text += std::to_string(sorted.size());
  *text += ";\n";
  *text += "\n";
}

void AppendDescTable(const std::vector<const OperatorSignature*>& sorted, std::string* text) {
  *text += "const GeneratedOperatorDesc kGeneratedOperators[] = {\n";
  for (const OperatorSignature* signature : sorted) {
    *text += "    {OperatorID::";
    *text += signature->opName;
    *text += ", \"";
    *text += signature->opName;
    *text += "\", \"";
    *text += signature->functionName;
    *text += "\", ";
    *text += signature->stage == "vertex" ? "true" : "false";
    *text += ", k";
    *text += signature->opName;
    *text += "Params, ";
    *text += std::to_string(signature->params.size());
    *text += "},\n";
  }
  if (sorted.empty()) {
    *text += "    // No //@op annotations yet; the table stays empty until the migration marks\n";
    *text += "    // its first operator.\n";
  }
  *text += "};\n";
  *text += "\n";
  *text += "const uint32_t kGeneratedOperatorCount = ";
  *text += std::to_string(sorted.size());
  *text += ";\n";
  *text += "\n";
  *text += "const GeneratedOperatorDesc* FindGeneratedOperator(const std::string& opName) {\n";
  *text += "  for (uint32_t index = 0; index < kGeneratedOperatorCount; ++index) {\n";
  *text += "    if (opName == kGeneratedOperators[index].opName) {\n";
  *text += "      return &kGeneratedOperators[index];\n";
  *text += "    }\n";
  *text += "  }\n";
  *text += "  return nullptr;\n";
  *text += "}\n";
}

void AppendEnsureUniformsImpl(const OperatorSignature& signature, std::string* text) {
  if (!HasUniformMembers(signature)) {
    return;
  }
  const std::string stage = signature.stage == "vertex" ? "ShaderStage::Vertex"
                                                        : "ShaderStage::Fragment";
  *text += "void ";
  *text += signature.opName;
  *text += "Op::EnsureUniforms(ProgramIRBuilder* ir, UniformHandler* uniformHandler,\n";
  *text += "                           ";
  *text += signature.opName;
  *text += "Op::UniformNames* textNames) {\n";
  const std::string& firstUniform = [&]() -> const std::string& {
    for (const auto& param : signature.params) {
      if (param.role == OperatorParamRole::Uniform ||
          param.role == OperatorParamRole::UniformArray) {
        return param.name;
      }
    }
    static const std::string none = {};
    return none;
  }();
  *text += "  if (!textNames->";
  *text += firstUniform;
  *text += ".empty()) {\n    return;\n  }\n";
  for (const auto& param : signature.params) {
    if (param.role != OperatorParamRole::Uniform && param.role != OperatorParamRole::UniformArray) {
      continue;
    }
    *text += "  textNames->";
    *text += param.name;
    *text += " = uniformHandler->addUniform(\"";
    *text += param.name;
    *text += "\", UniformFormat::";
    *text += UniformFormatNameOf(param.type);
    *text += ", ";
    *text += stage;
    if (param.role == OperatorParamRole::UniformArray) {
      *text += ", ";
      *text += std::to_string(param.arrayCount);
    }
    *text += ");\n";
    *text += "  ir->InternValue(textNames->";
    *text += param.name;
    *text += ", SLType::";
    *text += SLTypeNameOf(param.type);
    *text += ", Precision::High, IRValueKind::Uniform);\n";
  }
  *text += "}\n";
  *text += "\n";
}

void AppendEmitImpl(const OperatorSignature& signature, std::string* text) {
  *text += "ValueID ";
  *text += signature.opName;
  *text += "Op::Emit(ProgramIRBuilder* ir, UniformHandler* uniformHandler,\n";
  *text += "                     ";
  *text += signature.opName;
  *text += "Op::UniformNames* textNames, ";
  AppendEmitSignatureParams(signature, text);
  *text += ") {\n";
  if (HasUniformMembers(signature)) {
    *text += "  EnsureUniforms(ir, uniformHandler, textNames);\n";
  } else {
    *text += "  (void)uniformHandler;\n";
    *text += "  (void)textNames;\n";
  }
  for (const auto& param : signature.params) {
    if (param.role == OperatorParamRole::In && param.intLiteral) {
      *text += "  const auto ";
      *text += param.name;
      *text += "Value = ir->CreateIntConstant(";
      *text += param.name;
      *text += ");\n";
    }
  }
  for (const auto& param : signature.params) {
    if (param.role != OperatorParamRole::Uniform) {
      continue;
    }
    *text += "  const auto ";
    *text += param.name;
    *text += "Value = ir->InternValue(textNames->";
    *text += param.name;
    *text += ", SLType::";
    *text += SLTypeNameOf(param.type);
    *text += ", Precision::High, IRValueKind::Uniform);\n";
  }
  *text += "  return ir->CreateCall(OperatorID::";
  *text += signature.opName;
  *text += ", SLType::";
  *text += SLTypeNameOf(signature.returnType);
  *text += ", {";
  bool first = true;
  for (const auto& param : signature.params) {
    if (!first) {
      *text += ", ";
    }
    if (param.role == OperatorParamRole::In || param.role == OperatorParamRole::Sampler) {
      if (param.intLiteral) {
        *text += param.name;
        *text += "Value";
      } else {
        *text += param.name;
      }
    } else {
      *text += param.name;
      *text += "Value";
    }
    first = false;
  }
  *text += "});\n";
  *text += "}\n";
  *text += "\n";
}

void AppendUploadImpl(const OperatorSignature& signature, std::string* text) {
  if (!HasUniformMembers(signature)) {
    return;
  }
  *text += "void ";
  *text += signature.opName;
  *text += "Uniforms::upload(UniformData* uniformData) const {\n";
  for (const auto& param : signature.params) {
    if (param.role != OperatorParamRole::Uniform &&
        param.role != OperatorParamRole::UniformArray) {
      continue;
    }
    *text += "  uniformData->setData(\"";
    *text += param.name;
    *text += "\", ";
    *text += param.name;
    *text += ");\n";
  }
  *text += "}\n";
  *text += "\n";
}

