bool WriteGeneratedOperators(const std::vector<OperatorSignature>& signatures,
                             const std::string& outHeader, const std::string& outSource,
                             std::string* error) {
  std::vector<const OperatorSignature*> sorted = {};
  for (const auto& signature : signatures) {
    if (!IsPascalIdentifier(signature.opName)) {
      *error = "the operator name must be a Pascal-case identifier: " + signature.opName;
      return false;
    }
    if (SLTypeNameOf(signature.returnType) == nullptr) {
      *error = signature.opName + ": the return type '" + signature.returnType +
               "' has no SLType mapping";
      return false;
    }
    for (const auto& param : signature.params) {
      if (param.role == OperatorParamRole::Uniform) {
        if (UniformFieldCppType(param).empty()) {
          *error = signature.opName + ": the parameter '" + param.name +
                   "' has no C++ mapping";
          return false;
        }
      } else if (param.role == OperatorParamRole::UniformArray) {
        *error = signature.opName + ": the array parameter '" + param.name +
                 "' waits for the blur batch (Emit for arrays lands with it)";
        return false;
      } else if (param.role == OperatorParamRole::In && !param.intLiteral) {
        if (SLTypeNameOf(param.type) == nullptr) {
          *error = signature.opName + ": the parameter '" + param.name + "' has type '" +
                   param.type + "' with no SLType mapping";
          return false;
        }
      }
    }
    sorted.push_back(&signature);
  }
  std::sort(sorted.begin(), sorted.end(), OperatorNameLess);
  for (size_t index = 1; index < sorted.size(); ++index) {
    if (sorted[index]->opName == sorted[index - 1]->opName) {
      *error = "the operator name is declared twice: " + sorted[index]->opName;
      return false;
    }
  }

  std::string header = HeaderPrelude;
  AppendHeaderTypes(&header);
  for (const OperatorSignature* signature : sorted) {
    AppendUniformsStruct(*signature, &header);
  }
  for (const OperatorSignature* signature : sorted) {
    AppendEmitClass(*signature, &header);
  }
  header += "/// The runtime manifest table, generated from the same signatures as the glue above:\n";
  header += "/// the id enumerators stay hand-written in OperatorManifest.h (stable values); a missing\n";
  header += "/// enumerator or a signature drift fails the compile instead of surfacing at runtime.\n";
  header += "extern const OperatorDesc kGeneratedOperatorDescs[];\n";
  header += "extern const uint32_t kGeneratedOperatorDescCount;\n";
  header += "\n";
  header += HeaderEpilogue;

  std::string source = SourcePrelude;
  AppendParamTables(sorted, &source);
  AppendDescTable(sorted, &source);
  AppendManifestTable(sorted, &source);
  for (const OperatorSignature* signature : sorted) {
    AppendEnsureUniformsImpl(*signature, &source);
    AppendUploadImpl(*signature, &source);
    AppendEmitImpl(*signature, &source);
  }
  source += SourceEpilogue;

  return WriteIfChanged(outHeader, header, error) && WriteIfChanged(outSource, source, error);
}

