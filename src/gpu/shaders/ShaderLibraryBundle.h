#pragma once

#include <cstddef>
#include <cstdint>
#include <set>
#include <string>
#include <string_view>
#include <vector>
#include "gpu/ir/OperatorManifest.h"
#include "gpu/shaders/contract/ShaderLibraryBundleFormat.h"

namespace tgfx {

/**
 * The runtime view of the shader library bundle generated by shader_build_tool. The bundle carries
 * the artifacts of every target language in one file: function sources for the text languages and
 * one linkable module per operator for SPIR-V. This class exposes the section of the language the
 * current backend assembles. The data is embedded into the library at build time.
 */
class ShaderLibraryBundle {
 public:
  /// One precompiled operator module from the SPIR-V section: the linkable payload the Vulkan
  /// stitching route joins with the main it prints from the IR. Absent modules report a null data
  /// pointer, which the caller must treat as a build-contract violation, not as an empty shader.
  struct OperatorModule {
    const uint8_t* data = nullptr;
    size_t size = 0;
  };

  /// Returns the bundle embedded into this build, or an invalid bundle when none was embedded.
  static const ShaderLibraryBundle& Get();

  bool valid() const {
    return !_sections.empty();
  }

  bool hasLanguage(ShaderLibraryLanguage language) const;

  /**
   * Returns the number of functions in the language's section, or zero when the bundle carries no
   * such section.
   */
  size_t functionCount(ShaderLibraryLanguage language) const;

  /**
   * Appends one function and its transitive dependencies to out, callees before callers, and
   * records every appended function in emitted. The set belongs to one assembling shader.
   * @param language The target language section to read.
   * @param name The function name as the GLSL source declares it.
   * @param emitted The dedup set owned by the assembling shader.
   * @param out The function section the sources append to.
   * @return True when the function exists and was emitted (or was already emitted).
   */
  bool appendFunction(ShaderLibraryLanguage language, const char* name,
                      std::set<std::string>* emitted, std::string* out) const;

  /// Whether the language's section carries the named function, without emitting anything.
  bool containsFunction(ShaderLibraryLanguage language, const char* name) const;

  /**
   * Returns the operator's precompiled SPIR-V module from the SPIR-V section, or {nullptr, 0} when
   * the bundle carries no such section or no module for this operator. The module exports the
   * operator's manifest symbol with Export linkage and is ready for the SPIR-V linker.
   */
  OperatorModule findOperatorModule(OperatorID op) const;

 private:
  struct Function {
    std::string_view name = {};
    std::string_view source = {};
    std::string_view requires = {};
  };

  struct Section {
    ShaderLibraryLanguage language = ShaderLibraryLanguage::GLSL;
    std::vector<Function> functions = {};
  };

  ShaderLibraryBundle(const uint8_t* data, size_t size);

  static ShaderLibraryBundle CreateEmbedded();

  const Section* findSection(ShaderLibraryLanguage language) const;

  bool appendInSection(const Section& section, const char* name, std::set<std::string>* emitted,
                       std::string* out) const;

  std::vector<Section> _sections = {};
};

}  // namespace tgfx
