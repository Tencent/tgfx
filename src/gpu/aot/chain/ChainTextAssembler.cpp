// The assembled slice's operator vocabulary: the pointwise color operators, Blend, the inline
// expressions, the analytic coverage operators, plain texture leaves and the resource evaluators
// (gradients, noise). Tiled recipes and the macro-based color-space xform keep the interpreter's
// path until their entry material is packed too.
bool OpAssembles(int op) {
  switch (op) {
    case ChainISA::None:
    case ChainISA::ConstColor:
    case ChainISA::ColorMatrix:
    case ChainISA::Luma:
    case ChainISA::AlphaThreshold:
    case ChainISA::Blend:
    case ChainISA::InputOpaque:
    case ChainISA::MulAlpha:
    case ChainISA::AARectCoverage:
    case ChainISA::LocalRectCoverage:
    case ChainISA::RRectCoverage:
    case ChainISA::Texture:
    case ChainISA::TexModulate:
    case ChainISA::Gradient:
    case ChainISA::PerlinNoise:
    case ChainISA::ColorSpaceXform:
      return true;
    default:
      return false;
  }
}

// The pack entry's text copied out; an empty result means the entry is absent.
std::string PackText(const PrecompiledShaderCache* cache, uint32_t id) {
  const auto* blob = cache->findPackEntry(id);
  if (blob == nullptr) {
    return {};
  }
  return std::string(blob->data.begin(), blob->data.end());
}

bool ReplaceAll(std::string* text, const std::string& token, const std::string& value) {
  const auto position = text->find(token);
  if (position == std::string::npos) {
    return false;
  }
  text->replace(position, token.size(), value);
  return true;
}

// Leaf-position uniforms carry a _<leaf> suffix past the first leaf, matching the declaration
// walk's std140 members.
// The std140 type spelling of a plan parameter (the offsets' companion: the same rules the
// writer's accumulation follows).
const char* GlslTypeOf(FragmentType type) {
  switch (type) {
    case FragmentType::Float:
      return "float";
    case FragmentType::Float2:
      return "vec2";
    case FragmentType::Float3:
      return "vec3";
    case FragmentType::Float4:
      return "vec4";
    case FragmentType::Int:
      return "int";
    case FragmentType::Int4:
      return "ivec4";
    case FragmentType::Matrix3:
      return "mat3";
    case FragmentType::Matrix4:
      return "mat4";
  }
  return "vec4";
}

std::string LeafName(const char* base, int leaf) {
  return leaf == 0 ? std::string(base) : std::string(base) + "_" + std::to_string(leaf);
}

// One block member line, the same spelling the build's assembler emits (AppendBlockMember): the
// type, the assembled element name and the array count.
void AppendBlockMember(const Module* module, const Element& element, uint16_t count,
                       std::string* text) {
  *text += "  ";
  *text += ShaderTypeGlslName(element.type);
  *text += " ";
  *text += ElementNameOf(module, element);
  if (count > 1) {
    *text += "[" + std::to_string(count) + "]";
  }
  *text += ";\n";
}

// The declarations of one variant, generated by the same module walk the build's assembler and the
// runtime's layout derivation read — every declaration appears exactly once, in the walk's order,
// which is the writer's upload order.
struct GeneratedDeclarations {
  std::string uniformBlock;
  std::string varyings;
  std::string samplers;
  std::string colorVarying;  // empty when the geometry has none
  std::string coverageVarying;
  int samplerCount = 0;
  int chainDataWords = 0;
  bool hasSubsetVarying = false;
};

GeneratedDeclarations GenerateDeclarations(const Family& family, const Variant& variant,
                                           const ChainPlan& plan) {
  GeneratedDeclarations out = {};
  out.uniformBlock = "layout(std140) uniform FragmentUniformBlock {\n";
  const auto modules = ModulesOf(family, variant);
  for (uint8_t slot = 0; slot < modules.count; ++slot) {
    const Module* module = modules.list[slot];
    if (module == nullptr || !ModulePresent(family, variant, slot)) {
      continue;
    }
    const uint8_t dimBase = DimOffsetOf(family, variant, slot);
    for (uint8_t index = 0; index < module->elementCount; ++index) {
      const Element& element = module->elements[index];
      const bool present = ElementPresentInVariant(element, dimBase, variant);
      if (element.kind == Element::Kind::Varying) {
        // The GL dialect links varyings by name (the stored variant's dialect strips the
        // location qualifier), so the hole rule needs no spelling here — only the walk order.
        if (present) {
          const std::string name = VaryingNameOf(module, element);
          // The plan owns the varying contract: only the leaf coordinates the composition reads
          // and the resource coordinates (gradient/noise), so both stages carry the same set.
          bool keep = true;
          if (name.rfind("TransformedCoords_", 0) == 0) {
            keep = plan.leafVaryings.count(std::atoi(name.c_str() + 18)) != 0;
          } else if (name == "SourceCoords") {
            keep = plan.needsSourceCoords;
          }
          if (keep) {
            out.varyings +=
                std::string(" in ") + ShaderTypeGlslName(element.type) + " " + name + ";\n";
            if (name == "vColor") {
              out.colorVarying = name;
            } else if (name == "vCoverage") {
              out.coverageVarying = name;
            } else if (name == "vTexSubset") {
              out.hasSubsetVarying = true;
            }
          }
        }
      } else if (present && element.kind == Element::Kind::Param) {
        const auto count = ElementCountOf(element, dimBase, variant);
        AppendBlockMember(module, element, count, &out.uniformBlock);
        if (std::strcmp(element.name, "ChainData") == 0) {
          out.chainDataWords = count;
        }
      } else if (present && element.kind == Element::Kind::Texture) {
        // The GL dialect form: the stored variant's samplers carry no set/binding layout.
        out.samplers += " uniform sampler2D " + ElementNameOf(module, element) + ";\n";
        ++out.samplerCount;
      }
    }
  }
  out.uniformBlock += "};\n";
  out.samplers += "layout(location = 0) out vec4 fragColor;\n";
  return out;
}

