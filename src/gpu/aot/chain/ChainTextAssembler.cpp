bool AssembleChainVertexGLSL(const ChainPlan& plan, const std::string& storedVs,
                             std::string* code) {
  if (code == nullptr || storedVs.empty()) {
    return false;
  }
  // The stored vertex text is the rect geometry's exact interface (attributes, the vertex block,
  // the geometry hook); the plan supplies the varying contract: keep a varying line exactly when
  // the composition reads it, and write those varyings in the Chain hook.
  const std::string varyingHead = " out vec3 TransformedCoords_";
  std::string out;
  size_t cursor = 0;
  while (cursor < storedVs.size()) {
    const auto lineEnd = storedVs.find('\n', cursor);
    const std::string line = storedVs.substr(
        cursor, lineEnd == std::string::npos ? std::string::npos : lineEnd - cursor + 1);
    cursor = lineEnd == std::string::npos ? storedVs.size() : lineEnd + 1;
    if (line.rfind(varyingHead, 0) == 0) {
      const int leaf = std::atoi(line.c_str() + varyingHead.size());
      if (plan.leafVaryings.count(leaf) == 0) {
        continue;
      }
    } else if (line.rfind(" out vec3 SourceCoords;", 0) == 0 && !plan.needsSourceCoords) {
      continue;
    }
    out += line;
  }
  std::string hookBody;
  for (int leaf : plan.leafVaryings) {
    hookBody += "  TransformedCoords_" + std::to_string(leaf) + " = (CoordTransformMatrix_" +
                std::to_string(leaf) + " * vec3(v.localCoord, 1.0)).xyz;\n";
  }
  if (plan.needsSourceCoords) {
    hookBody += "  SourceCoords = (CoordTransformMatrix_0 * vec3(v.localCoord, 1.0)).xyz;\n";
  }
  const auto hookAt = out.find("void Chain_vertex(inout Vertex v) {");
  if (hookAt == std::string::npos) {
    return false;
  }
  const auto bodyAt = out.find('\n', hookAt) + 1;
  const auto hookEnd = out.find("}\n", bodyAt);
  if (hookEnd == std::string::npos) {
    return false;
  }
  out = out.substr(0, bodyAt) + hookBody + out.substr(hookEnd);
  *code = out;
  return true;
}

bool AssembleChainFragmentGLSL(const ChainPlan& plan, const ChainComposition& composition,
                               const Family& family, const Variant& variant,
                               const PrecompiledShaderCache* cache, std::string* code) {
  if (code == nullptr) {
    return false;
  }
  // The rect-geometry slice: the aliased rect layouts whose color and coverage arrive as varyings.
  // The declared geometries (their own modules' fragment hooks) come with the geometry prelude
  // table, not this slice.
  if (variant.geometry != 0) {
    return false;
  }
  // Shader-tiled leaves need the tiling module's runtime loops, which the pack does not spell.
  if ((composition.textureFlags & 2) != 0) {
    return false;
  }
  for (const auto& slot : composition.slots) {
    if (!OpAssembles(slot.op)) {
      return false;
    }
  }
  const std::string tail = PackText(cache, FragmentPackTail);
  if (tail.empty()) {
    return false;
  }
  // The xfer fact picks the resolved support entry: 1 reads the dst through the texture, 2 through
  // framebuffer fetch; 0 carries none.
  const uint8_t xferSlot = static_cast<uint8_t>(2 + family.moduleCount);
  const int hasXp = DimValueOf(family, variant, xferSlot, 0);
  std::string xpSupport;
  if (hasXp == 1) {
    xpSupport = PackText(cache, FragmentPackXpDstTexture);
  } else if (hasXp == 2) {
    xpSupport = PackText(cache, FragmentPackXpFramebufferFetch);
  } else if (hasXp != 0) {
    return false;
  }
  if (hasXp != 0 && xpSupport.empty()) {
    return false;
  }
  // The used ops' pack entries, each at most once: the pure fragments, the resource evaluators
  // (already include-expanded), and the shared dependencies the coverage fragments call into.
  const std::set<int>& usedOps = plan.usedOps;
  bool needsTexture = plan.hasTexture;
  bool needsAnalytic = usedOps.count(ChainISA::LocalRectCoverage) != 0 ||
                       usedOps.count(ChainISA::RRectCoverage) != 0;
  std::string pieces;
  auto appendPiece = [&](uint32_t id) {
    const std::string text = PackText(cache, id);
    if (text.empty()) {
      return false;
    }
    pieces += text + "\n";
    return true;
  };
  if (needsTexture && !appendPiece(FragmentPackDepTextureSwizzle)) {
    return false;
  }
  if (needsTexture && !appendPiece(FragmentPackDepTextureSampling)) {
    return false;
  }
  // The leaf fetch form follows the variant's strict-subset fact: only a variant declaring the
  // per-quad subset varying carries the extra clamp.
  if (needsTexture) {
    // Selected after the walk below (it needs the declarations), so it is deferred there.
  }
  if (needsAnalytic && !appendPiece(FragmentPackDepAnalyticClipMath)) {
    return false;
  }
  if (!xpSupport.empty()) {
    pieces += xpSupport + "\n";
  }
  for (int op : usedOps) {
    const auto* def = FindFragment(op);
    if (def == nullptr) {
      continue;
    }
    // The gradient evaluator's packed form is chosen by the variant's leaf capacity (its LUT
    // branch samples the leaf-0 texture), so it is appended after the walk instead.
    if (op == ChainISA::Gradient) {
      continue;
    }
    if (def->sourceFile == nullptr) {
      continue;
    }
    if (!appendPiece(0x40000000u | static_cast<uint32_t>(op))) {
      return false;
    }
  }
  // The leaf prefetches: plain fetches at the leaf positions, through the packed helper.
  std::string prefetch;
  for (size_t index = 0; index < composition.slots.size() && index < 4; ++index) {
    if (composition.slots[index].op != ChainISA::Texture) {
      continue;
    }
    const std::string leaf = std::to_string(index);
    prefetch += "  chainLeafTex[" + leaf + "] = chainPlainLeafFetch(TextureSampler_" + leaf +
                ", TransformedCoords_" + leaf + ", " + LeafName("Subset", static_cast<int>(index)) +
                ", " + LeafName("AlphaStart", static_cast<int>(index)) + ", " +
                LeafName("HasRgbaaa", static_cast<int>(index)) + ", " +
                LeafName("SubsetClampOn", static_cast<int>(index)) + ", " + leaf + ");\n";
  }
  // The declarations come first: they pick the packed forms below.
  auto declarations = GenerateDeclarations(family, variant, plan);
  // The plan's parameter members join the block past the prefix (their offsets start at the
  // prefix's fragment block size, which std140 rounds to the same boundary the driver computes).
  if (!plan.params.empty()) {
    std::string paramMembers;
    for (const auto& param : plan.params) {
      paramMembers += std::string("  ") + GlslTypeOf(param.type) + " " + param.member + ";\n";
    }
    const auto closeAt = declarations.uniformBlock.rfind("};");
    if (closeAt == std::string::npos) {
      return false;
    }
    declarations.uniformBlock.insert(closeAt, paramMembers);
  }
  // The straight-line body: one call per slot, the arguments naming members, locals and literals.
  std::string body;
  for (const auto& call : plan.calls) {
    const auto* def = FindFragment(call.op);
    if (def == nullptr) {
      return false;
    }
    if (call.op == ChainISA::InputOpaque) {
      body += "  vec4 " + call.out + " = vec4(" + call.args[0] + ".rgb, 1.0);\n";
    } else if (call.op == ChainISA::MulAlpha) {
      body += "  vec4 " + call.out + " = " + call.args[0] + " * " + call.args[1] + ".a;\n";
    } else {
      std::string args;
      for (size_t index = 0; index < call.args.size(); ++index) {
        if (index != 0) {
          args += ", ";
        }
        args += call.args[index];
      }
      body += "  vec4 " + call.out + " = " + def->functionName + "(" + args + ");\n";
    }
    if (!call.sink.empty()) {
      body += "  " + call.sink + " = " + call.out + ";\n";
    }
    if (!call.post.empty()) {
      body += "  " + call.post + "\n";
    }
  }
  if (plan.xpNeedsBlendPass) {
    body += "  chainXPSrc = chainXPSrcUnpremul(result, coverageRootRegister);\n";
    body += "  xpBlended = xpBlendColors(chainXPSrc, chainXPDst, XPBlendMode);\n";
  }
  if (body.empty() && !composition.slots.empty()) {
    return false;
  }
  if (usedOps.count(ChainISA::Gradient) != 0) {
    const bool keepLut = declarations.samplerCount > 0;
    if (!appendPiece(keepLut ? FragmentPackGradientLut : FragmentPackGradientSimple)) {
      return false;
    }
  }
  if (needsTexture) {
    if (!appendPiece(declarations.hasSubsetVarying ? FragmentPackLeafFetchStrict
                                                   : FragmentPackLeafFetchPlain)) {
      return false;
    }
  }
  // The fixed designator sources for the rect geometry: the common-color-or-vertex-color
  // selection and the coverage varying (the vec4(1.0) form keeps the no-coverage variants valid).
  const std::string colorExpr = declarations.colorVarying.empty()
                                    ? "ChainColorParams_Color"
                                    : "(ChainColorParams_HasCommonColor != 0) ? "
                                      "ChainColorParams_Color : " +
                                          declarations.colorVarying;
  const std::string unitExpr = declarations.coverageVarying.empty()
                                   ? "vec4(1.0)"
                                   : "vec4(" + declarations.coverageVarying + ")";
  std::string sources;
  sources += "vec4 chainGeomColorSource() {\n  return " + colorExpr + ";\n}\n\n";
  sources += "vec4 chainUnitCoverageSource() {\n  return " + unitExpr + ";\n}\n\n";
  sources += "vec4 chainOpaqueGeomColorSource() {\n  vec4 color = " + colorExpr +
             ";\n  return vec4(color.rgb, 1.0);\n}\n\n";
  sources +=
      "vec4 chainXPSrcUnpremul(vec4 result, vec4 coverageRootRegister) {\n  return (SPEC"
      "_PLACEHOLDER_COVERAGE_ROOT_ >= 0 ? result * coverageRootRegister : result);\n}\n";
  // The rect geometry contributes coverage through its varying, so a coverage subtree's root
  // replaces it in the tail; the xfer source function's coverage-root modulation form only
  // matters for the geometries without one, so the placeholder resolves to the same fact.
  ReplaceAll(&sources, "SPEC_PLACEHOLDER_COVERAGE_ROOT_",
             composition.coverageRootRegister >= 0 ? "1" : "0");
  // The tail's three placeholders: the clip coverage, the final coverage before the clip folds in,
  // and the output statement.
  const std::string clip = composition.clipCoverageRegister >= 0 ? "clipRegister" : "vec4(1.0)";
  const std::string coverage =
      composition.coverageRootRegister >= 0 ? "coverageRootRegister" : "chainUnitCoverageSource()";
  const std::string src = "result";
  std::string output;
  if (hasXp != 0 && composition.xpNeedsBlendPass) {
    output =
        "  fragColor = xpCompositeBlendPass(" + src + ", chainXPDst, finalCoverage, xpBlended);";
  } else if (hasXp != 0) {
    output = "  fragColor = applyPorterDuffXP(" + src + ", finalCoverage);";
  } else {
    output = "  fragColor = (" + src + " * finalCoverage);";
  }
  std::string tailText = tail;
  if (!ReplaceAll(&tailText, "__TGFX_CLIP_COVERAGE__", clip) ||
      !ReplaceAll(&tailText, "__TGFX_FINAL_COVERAGE__", coverage) ||
      !ReplaceAll(&tailText, "__TGFX_OUTPUT__", output)) {
    return false;
  }
  // The xfer's dst globals (the interpreter region declares them; here the wrapper does).
  std::string xpGlobals;
  std::string xpLocals;
  if (hasXp != 0) {
    xpGlobals = "vec4 chainXPDst = vec4(0.0);\nvec4 chainXPSrc = vec4(0.0);\n";
    xpLocals = "  chainXPDst = xpReadDstColor();\n  vec4 xpBlended = vec4(0.0);\n";
  }
  *code = "#version 330\n#define TGFX_DECLARED_CHAIN 1\n" + declarations.uniformBlock +
          declarations.varyings + declarations.samplers + "\n" + sources + pieces +
          "vec4 chainLeafTex[4];\n" + xpGlobals +
          "\nvoid main() {\n"
          "  vec4 result = vec4(0.0);\n"
          "  vec4 clipRegister = vec4(0.0);\n"
          "  vec4 coverageRootRegister = vec4(0.0);\n" +
          xpLocals + prefetch + body + tailText + "}\n";
  // The dump aid: with TGFX_ASSEMBLED_DUMP pointing at a directory, every assembled text lands
  // there as assembled_N.glsl for inspection. Read-only diagnostic, no effect on the pipeline.
  if (const char* dumpDir = std::getenv("TGFX_ASSEMBLED_DUMP")) {
    static std::atomic<int> dumpCount = {0};
    const int index = dumpCount.fetch_add(1);
    std::ofstream file(std::string(dumpDir) + "/assembled_" + std::to_string(index) + ".glsl",
                       std::ios::binary);
    file << *code;
  }
  return true;
}

